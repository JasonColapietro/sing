const body = `## How to sing karaoke: the short answer

To sing karaoke well, pick a song whose chorus sits in the comfortable middle of your voice, set the key to suit you, and practice it before the night instead of meeting it on the screen. Hold the microphone close and pointed at your mouth, warm up quietly before your turn, and pace yourself so your voice lasts. Nerves are normal; a song you know cold is the best cure for them.

Most bad karaoke moments come from one of four things: a song that is too high or too low, a song you only half know, a microphone held in the wrong place, or a voice already worn out from shouting over the music. Each has a simple fix, and this guide takes them in order.

## Pick a song that fits your voice

Song choice decides most of how your turn goes. The song that sounds great on the radio is not always the one that sounds great in your voice.

### Know your range first

Take the [vocal range test](/range?mode=range#start) before you build a list. It shows your lowest and highest notes, and more usefully, where your voice is comfortable. Then compare songs with that range on the [can you sing it](/can-you-sing) pages, which lay out the range of popular songs so you can see whether one fits before you get on stage.

::infographic songs

### Look at the chorus, not just the top note

A song's highest note may come once. The chorus comes three or four times. What tires a voice is the [tessitura](/glossary#tessitura), the area where the melody spends most of its time. [Someone You Loved](/can-you-sing/someone-you-loved) only spans an octave and a fifth, but its chorus keeps a male voice parked high and holding there. [Hallelujah](/can-you-sing/hallelujah) has a modest range, so the challenge is quiet control rather than reach. [Flowers](/can-you-sing/flowers) sits low, which suits darker voices and can lose lighter ones.

### Rules of thumb for a karaoke song

- You know every word and every entrance without reading.
- The chorus feels easy at a moderate volume in your practice key.
- The hardest moment is short, and you have practiced it.
- It is fun for the room. A song people know and like buys a lot of goodwill.
- It has no long instrumental stretches you will not know what to do with.

Save the showstoppers for later. A song like [I Will Always Love You](/can-you-sing/i-will-always-love-you) has long unaccompanied phrases and a key change that lifts the last chorus to a belted climax near the top of the soprano break. [Shallow](/can-you-sing/shallow) is simple until the bridge, which asks for a wide-open belt. Those are great songs to work toward, not songs to try cold.

## Use the key control

Many karaoke systems and apps have a key or pitch control that moves the track up or down in semitones. Singing in your own key is not cheating; professional singers do it all the time. The lesson [your key, not the record's key](/learn/voice/steady-tone/first-song-one-register/your-key-not-the-records-key) explains the idea, and the glossary entry on [transposition](/glossary#transposition) defines it.

How to use it:

- **Find your number at home.** Practice with a karaoke version of the song and try your best guess, then one semitone higher and one lower. Sing the chorus, not just the verse, at each step. Write down the number, such as "minus 2".
- **Check the low end too.** Lowering a song for the chorus also lowers the verse. Make sure the lowest verse note is still clear.
- **Tell the host.** In many bars the host sets the key from their desk. Say the number when you hand in your song.
- **Keep shifts modest.** A large shift can make some tracks sound odd. If you need more than a few semitones, a different song may suit you better.

### Songs written for another voice

If a song was recorded by a singer in a different octave from yours, you can sing it an octave lower or higher. Then use the key control to fine-tune it so the chorus sits well. A few semitones usually does it.

### Songs with a key change inside them

Many pop songs lift the key for the last chorus. That final chorus is the one that matters, so practice it first. If it strains, lower the whole song before you start.

## Practice the song before the night

The singers who sound relaxed at karaoke usually practiced. A week of short sessions is plenty.

::infographic practice

Record yourself in the [recorder](/recorder) partway through the week and listen back. The places where you rush, run out of breath or go flat are the places to practice. Hold the hardest note in the [pitch studio](/studio) and watch the cents readout until it lands in the center. If pitch is your weak spot in general, [how to sing on pitch](/guides/how-to-sing-on-pitch) has drills for it.

Practice standing up with your phone or a hairbrush held where the microphone will be. It sounds silly, and it helps: your body learns where your hand goes, and you stop thinking about it on the night.

## How to hold the microphone

A karaoke microphone is usually a handheld dynamic mic. These pick up most clearly when you are close and pointed straight at them.

- **Close and centered.** Hold it about an inch or two from your lips, pointed at your mouth. Far away, you sound thin and you are tempted to push.
- **Hold the handle, not the head.** Cupping the round grille muffles your sound and makes feedback, that loud whistle, more likely.
- **Back off for loud notes.** Move the mic a little further away on a big high note and back in for quiet lines, so the volume stays even.
- **Keep it pointed at you.** When you look at the screen or the crowd, turn your head and the mic together.
- **Stay clear of the speakers.** Walking in front of a speaker with the mic is the usual cause of feedback.

::video mic

For more on distance, angle and hearing yourself, read [how to sing into a microphone](/guides/how-to-sing-into-a-microphone). The lesson on [mic distance as a dynamic control](/learn/voice/signature/the-room/mic-distance-is-a-dynamic-control) has a short drill you can do at home.

### When you cannot hear yourself

Bars are loud, and many karaoke setups have no monitor speaker pointed at the singer. If you cannot hear yourself, put one finger lightly over one ear. You will hear your own voice more clearly through your head, and your pitch will usually improve. Avoid pushing louder to hear yourself, which tires the voice fast.

## Warming up in a bar

You do not need a full warm-up routine, and you should not do scales at the table. A quiet five minutes before your turn is enough.

- **In the car or on the walk over**, run the [quick warm-up routine](/warmups?routine=quick) or hum gently up and down a comfortable range.
- **Lip trills or a straw** are quiet and effective. A few minutes in a hallway or outside helps.
- **Hum the first line** of your song at a low volume just before you go up.
- **Talk less, not louder.** Shouting conversation over the music is often harder on your voice than the singing. Lean in, speak at a normal level, or step outside to talk.

## Handling nerves

A shaky voice, a dry mouth and fast breathing before your turn are your body getting ready to perform. They are normal, and they usually ease after the first line.

- **Pick a first song you know cold.** Save the riskier choice for later in the night.
- **Breathe out slowly.** A few long, slow exhales before you start calm your breathing more than deep gulps of air.
- **Know your first line.** Hum it under your breath while the intro plays so you start on the right note.
- **Sing to one friendly face.** It is easier than singing to a room.
- **Keep going.** If you miss a line, pick up at the next one. Almost nobody remembers mistakes at karaoke.

::video nerves

For a longer plan, read [how to overcome stage fright when singing](/guides/how-to-overcome-stage-fright-when-singing).

## Pacing a karaoke night

A long night of singing, talking and cheering adds up to a large [vocal dose](/glossary#vocal-dose). Plan the night so you still have a voice for your last song and the next morning.

::infographic pacing

About alcohol: many people say it helps them loosen up, but it dries the voice and dulls your sense of pitch, so you sound less in tune than you think. If you drink, have water alongside it, and do not count on it to make you sing better.

## Common karaoke mistakes and how to fix them

| Mistake | What happens | Fix |
|---|---|---|
| Song too high | Chorus strains, voice cracks or shouts | Lower the key or choose another song |
| Song barely known | Late entrances, eyes glued to the screen | Practice it for a week before the night |
| Mic held far away | Thin sound, you push to be heard | Hold it an inch or two from your lips |
| Cupping the mic | Muffled sound and feedback | Hold the handle, not the grille |
| Starting with the hardest song | Nerves and a cold voice meet the hardest notes | Open with an easy favorite |
| Shouting over the music all night | Hoarse by the third song | Talk less, drink water, step outside to chat |

If your throat feels raw or you are hoarse the next day, rest your voice and read [sore throat after singing](/guides/sore-throat-after-singing). Hoarseness that lasts more than about two weeks, or pain when you sing, is a reason to see a doctor.

## Keep getting better between nights

Karaoke is a good reason to practice. Pick the next song you want to sing, check it on the [can you sing it](/can-you-sing) pages, and give it a week. Retake the [range test](/range?mode=range#start) every couple of months to see your comfortable range grow. To test your range on your phone, the Suede Voice app for iPhone and Android is on the [Suede Voice page](/voice). Then pick a song that makes you happy and go enjoy it.`;

