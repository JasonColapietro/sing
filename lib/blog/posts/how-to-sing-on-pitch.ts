const body = `## How to sing on pitch: the short version

To sing on pitch, you need two things working together: an ear that can hold the target note in your head, and a voice that can land on that note and stay there. Most people who sing off-key have a gap in one of them, and both can be trained. The method in this article is simple. Hear the note before you sing it, match it against a steady reference, check yourself with a cents readout, and repeat in short, frequent sessions.

To find out where you stand right now, play a mid-range note on a keyboard, stop it, sing it back on "ah" and check the cents readout in the [pitch studio](/studio). Do it five times. If most attempts land within about 25 cents, your ear and voice already connect and you need steadiness. If you keep landing on a different note, start with the hearing drills. If you have been told you are "tone deaf," read the next section before you give up. Then work through the drills, the 7-day plan and the troubleshooting table. Everything here can be practiced in your browser with the [pitch studio](/studio), the [ear training games](/ear-training) and the drone in [practice tools](/tools).

## Why you sing flat or sharp

Singing out of tune feels like one problem. It is usually one of three, and each has its own fix.

### Hearing: the target is fuzzy

Your brain needs a clear picture of the note before your voice can aim at it. If you start singing at the same moment you hear the note, you are guessing, and the voice searches for the pitch out loud. Singers with this gap often sing a different note entirely, or settle on the right note's neighbor, and do not notice until they hear a recording.

### Production: the voice drifts

Many singers hear the note perfectly well and still miss it. The usual culprits are physical:

- **Falling breath energy.** As air runs out at the end of a phrase, pressure drops and the pitch sags flat. This is the classic "fine at the start, flat by the end" pattern.
- **Reaching for high notes.** Squeezing or pushing near the top of your range tends to pull notes flat (or, if you overdrive it, sharp).
- **Low notes with no energy.** Notes at the bottom of your range often sag because they get sung with less attention.
- **Scooping.** Sliding up into every note from underneath. Each note ends up in tune, but the front of it is not.

### Monitoring: you cannot hear yourself

A loud backing track or band can cover your voice in your own ears, so you lose the feedback you need to correct. If you sing well alone and poorly with music, monitoring is the likely issue. Loud playback also leaks into the microphone and skews any pitch meter. The lesson on [why loud playback ruins pitch](/learn/voice/room-check/set-up-your-space/why-loud-playback-ruins-pitch) shows how to set speaker volume and headphones so both your ears and the meter hear your voice clearly.

### What about tone deafness?

True tone deafness (congenital amusia) is a real but uncommon condition. Published estimates range from about 1.5 to 4 percent of people, depending on how it is tested. People with amusia usually struggle to tell whether two notes are the same or different, and often cannot recognize familiar tunes without the words. If you can hear that someone else is singing off-key, or you can tell when you yourself are wrong on a recording, you are very unlikely to be in that group. For a closer check, play Higher or lower on Hard in [ear training](/ear-training), where the second note is a semitone above, a semitone below or the same. If you can tell those apart reliably, your pitch hearing works and what you have is an untrained skill.

::infographic three-ways-off

## How to read a cents readout

A semitone, the distance between two neighboring piano keys, is divided into 100 cents. The [pitch studio](/studio) shows how many cents sharp (+) or flat (-) you are at every moment, and draws an 8-second trace so you can see the shape of each note. Read the [glossary entry for cent](/glossary#cent) if the unit is new to you.

What the numbers mean in practice:

- **Within about ±10 cents:** you are on the note. On a sustained, exposed tone, trained ears may notice something around this size; in a moving line, almost nobody will.
- **Around ±25 cents:** a quarter of the way to the next key. Audible on long held notes, especially against a piano or a harmony part. This is the zone to work out of.
- **Around ±50 cents:** halfway to the next note. Most listeners hear this as out of tune. If you sit here on a long note, the room will notice.
- **Around 100 cents off and steady:** you have probably sung a neighboring note. That is a hearing or note-choice problem, not a tuning one.

::infographic cents-scale

Do not chase zero. No voice holds dead still, and a healthy vibrato swings above and below the center several times a second, so the readout will flicker sharp and flat around the target. Look at where the trace is centered. The book chapter on [when the numbers lie](/book/when-numbers-lie) explains the meter's blind spots in more depth.

## Pitch matching with a drone

A drone is one sustained note that does not stop. It is one of the most useful tools for learning to sing on pitch because it gives your ear a reference to rub against. When you are slightly off, you hear a slow wavering or "beating" against the drone. When you are on, the two sounds lock and the beating disappears.

Open the drone in [practice tools](/tools), set it to a comfortable note in the middle of your voice (around A3 to C4 for many lower voices, F4 to A4 for many higher ones), and keep the volume moderate so you can still hear yourself.

::infographic drone-method

### Drill 1: Unison hum (5 minutes)

1. Let the drone sound for three seconds while you listen without singing.
2. Hum the note at a medium-soft volume for 5 to 8 seconds.
3. Listen for beating. If you hear it, slide very slowly up or down until it goes away.
4. Stop, breathe, and repeat 10 times.

Humming first keeps effort low so you can focus on listening. When the hum locks reliably, switch to an "oo" vowel, then "ah."

### Drill 2: Bend and return (3 minutes)

Sing the drone note, then bend your pitch slowly up by a small amount and come back, then down and back. Do 6 bends each way. This teaches you what "sharp" and "flat" feel like from the inside, which is exactly the skill you need to correct yourself mid-phrase.

### Drill 3: Silent target (5 minutes)

Hear the note on the drone or keyboard, stop it, wait two seconds, then sing it from silence. Check the [pitch studio](/studio) cents readout at the instant the sound starts. This mirrors the course lesson [hear the pitch before you sing](/learn/voice/pitch-time-words/in-tune-all-the-way/hear-the-pitch-before-you-sing), and it is the drill that transfers most directly to real songs, where nobody hands you a drone.

## Land the note without scooping

Scooping is sliding into a note from below. A deliberate scoop is a style choice in pop, soul and country. An accidental one on every note makes you sound unsure and costs you accuracy on the front of each note. The [glossary entry on scoop](/glossary#scoop) has the definition; here is the fix.

### Drill 4: Land from above (4 minutes)

In Target practice in the pitch studio, pick a mid-range note. Sing it 8 times. On the first four, use your normal onset. On the last four, imagine the note slightly above where you think it is, and arrive on it cleanly with a gentle start, as if saying "ah" after a small, relaxed breath. Watch the front edge of the trace. If the hook at the start shrinks, you have found your habit.

The course lesson [match five, no scoop](/learn/voice/steady-tone/land-the-note/match-five-no-scoop) turns this into a five-note pattern, and [onset without the click](/learn/voice/steady-tone/land-the-note/onset-without-the-click) helps if your clean starts turn hard or throaty.

## Interval training: in tune between notes

Single notes are the foundation. Songs, though, are built from jumps between notes, and most pitch errors happen on the jump. An interval is the distance between two notes, and every one has its own sound. A perfect fifth is the opening of "Twinkle Twinkle Little Star." An octave is the leap at the start of "Somewhere Over the Rainbow."

### Drill 5: Step, then skip (5 minutes)

1. Sing do-re-mi-fa-sol and back down on "nee," slowly, with the drone on do.
2. Then sing do-mi-sol-mi-do (a major arpeggio).
3. Then do-sol-do, the fifth on its own.
4. Each time, hold the top note for two seconds and check it in the studio.

The drone makes this easier because every note has a fixed relationship to it. Fifths sound smooth and stable over the drone; thirds have a sweeter color. When a note sounds "rough" against the drone, it is usually off.

### Drill 6: Ear training games (5 minutes)

The [ear training](/ear-training) room has short games for matching pitch, catching moving notes, naming intervals and singing melodies back. Five minutes a day here builds the listening half of the skill, so your voice has a sharper target to aim at.

## Hold the note steady

Many singers hit the note and then wander. The usual cause is breath and effort rather than the ear. The fix is steadier airflow at a moderate volume.

- **Straw phonation or lip trills.** Semi-occluded exercises (SOVT) such as singing through a straw or doing lip trills balance pressure above and below the vocal folds, making a steady tone easier. Start with the lesson on [straw and lip trill](/learn/voice/steady-tone/straw-and-lip-trill), then sing the same note on an open vowel.
- **One note per bar.** Hold a single note for four slow beats, rest four, repeat 8 times. The lesson [one note per bar](/learn/voice/steady-tone/hold-it/one-note-per-bar) walks through this.
- **Watch the tail.** In the studio trace, notes that drift flat at the end tell you that breath energy is dropping. Shorten the phrase, take a fresh breath, and rebuild length gradually.

If a whole phrase drifts, the [drift correction lesson](/learn/voice/pitch-time-words/in-tune-all-the-way/drift-correction) has you hear a sustained reference, sing from silence and compare fresh attempts by ear.

## Record yourself and listen back

You sound different to yourself than to a listener, because part of your own sound reaches your ears through the bones of your head. While you sing, your attention is also split between making the sound and judging it. A recording lets you do only the judging.

Use the [recorder](/recorder) to capture one short phrase a day, the same phrase each time. Listen once for pitch only. Ask:

- Did each note start on pitch, or slide in?
- Did long notes stay put, or sink at the end?
- Did the hardest leap land, or overshoot?

A simple song works well here. "Amazing Grace" is a classic for a reason: it has a clear melody, a few wide leaps and long notes. Practice the [Amazing Grace song page](/songs/amazing-grace) in a comfortable key, and use the lesson [Amazing Grace: a phrase to study](/learn/voice/steady-tone/first-song-one-register/amazing-grace-phrase-to-study) for one phrase at a time. When that feels solid, test yourself on a familiar ballad such as [Hallelujah](/can-you-sing/hallelujah), whose page shows whether the song sits inside your range.

## A 7-day plan to sing on pitch

Twenty minutes a day, every day, beats two hours on Sunday. Short, frequent sessions let both your ear and your coordination settle.

::infographic seven-day-plan

| Day | Focus | Drills (about 20 minutes) | Measure |
|---|---|---|---|
| Day 1 | Baseline | Take the [range test](/range?mode=range#start); record one phrase | Save the recording and note your comfortable middle |
| Day 2 | Unison | Drill 1 unison hum, Drill 2 bend and return | Cents readout settles within ±25 on hums |
| Day 3 | Silent target | Drill 3 silent target, 20 reps | Count how many starts land within ±25 |
| Day 4 | Onsets | Drill 4 land from above; straw warmup | Hook at the front of the trace shrinks |
| Day 5 | Intervals | Drill 5 step then skip; Drill 6 games | Top notes held within ±25 for two seconds |
| Day 6 | Steady tone | Lip trills, one note per bar, drift correction | Trace stays flat through the end of each hold |
| Day 7 | Song | Sing your chosen phrase; record it | Compare with Day 1 recording by ear |

Keep every note in the comfortable middle of your voice this week. Accuracy on easy notes comes first; range work can wait. If you want warmups to start each session, the [warmups](/warmups) room has guided routines.

## Common mistakes and fixes

> Most pitch problems come down to attention, effort and feedback.

- **Singing too loud.** Volume adds effort and hides pitch errors from your own ears. Practice at medium-soft volume first.
- **Practicing only with the backing track.** The track covers your mistakes. Use the drone and a cappella attempts, then add the music back.
- **Choosing songs in the wrong key.** If the song sits too high or low, you will miss notes for physical reasons. Transpose to your key.
- **Staring at the meter while singing.** Use the readout to check, then sing with your eyes closed and check again. The goal is an ear that works without the screen.
- **Correcting by sliding.** When you notice you are off, stop and start again rather than slithering to the note. Fresh, clean attempts build accuracy faster.

::infographic do-avoid

## How to measure progress

Measure the same thing the same way every week so changes are real:

1. **Silent-target score.** Out of 20 starts from silence, how many land within ±25 cents in the [pitch studio](/studio)? Write it down.
2. **Steady hold.** How long can you hold a mid-range note with the trace inside the target lane?
3. **Recording comparison.** Play this week's recording next to the first one. You should hear cleaner starts and fewer sinking endings.
4. **Interval accuracy.** In [ear training](/ear-training), track how often you sing intervals back correctly.

Progress is usually uneven. You may jump forward in a week, then plateau. That is normal. Keep the sessions short and regular.

## Learn from great intonation

Listening is training too. [Ella Fitzgerald](/singers/ella-fitzgerald) was famous for precise tuning even in fast scat lines, and her recordings are a model of clean onsets. [Adele](/singers/adele) holds long, exposed notes with steady pitch in ballads like "Someone Like You." Pick one phrase, play it, then sing it back on a single vowel over the drone set to the song's key.

::video ramsey-pitch

## When to see a voice teacher or doctor

A voice teacher is worth it if you have practiced daily for several weeks and pitch still slips in the same places, or if you want help with register changes that throw you off. A teacher can hear patterns that a meter cannot, like tension in the jaw or tongue.

See a doctor, ideally an ENT or laryngologist, if you have hoarseness lasting more than about two weeks, pain when you sing or speak, or a sudden loss of voice. Pitch accuracy drills should never hurt. If they do, stop and get checked.

## Start today

Pick one note in the middle of your voice. Turn on the drone, hum until the beating stops, then try ten starts from silence in the studio. Write down how many land. That number is your baseline, and it will move.`;

